#!/usr/bin/env python3
import argparse
import datetime
import hashlib
import hmac
import http.client
import os
import pathlib
import socket
import subprocess
import tempfile
import time
import urllib.parse
import xml.etree.ElementTree as ET

from auth_regression import ACCESS_KEY, SECRET_KEY, sign
from presign import presign


PROJECT = pathlib.Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description="Test presigned URLs against a temporary authenticated server.")
    parser.add_argument("--sdk", action="store_true", help="also verify URLs generated by installed botocore")
    arguments = parser.parse_args()
    subprocess.run(["moon", "build", "cmd/main", "--target", "native"], cwd=PROJECT, check=True)
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", 0))
        port = listener.getsockname()[1]
    host = f"127.0.0.1:{port}"
    endpoint = "http://" + host
    object_key = "folder/头像 +%&.txt"
    object_path = "/presign-bucket/" + urllib.parse.quote(object_key, safe="/")

    def request(method, target, body=b"", headers=None):
        address = urllib.parse.urlsplit(target)
        path = address.path + ("?" + address.query if address.query else "")
        connection = http.client.HTTPConnection("127.0.0.1", port, timeout=5)
        try:
            connection.request(method, path, body=body, headers=headers or {})
            response = connection.getresponse()
            return response.status, dict(response.getheaders()), response.read()
        finally:
            connection.close()

    def url(method="GET", key=object_key, **options):
        return presign(endpoint, "presign-bucket", key, ACCESS_KEY, SECRET_KEY, method=method, **options)

    def changed(target, name, value):
        address = urllib.parse.urlsplit(target)
        parameters = urllib.parse.parse_qsl(address.query)
        parameters = [(param, value if param == name else original) for param, original in parameters]
        return urllib.parse.urlunsplit(address._replace(query=urllib.parse.urlencode(parameters, quote_via=urllib.parse.quote)))

    def resign(target, method="GET", headers=None):
        address = urllib.parse.urlsplit(target)
        parameters = urllib.parse.parse_qsl(address.query)
        values = dict(parameters)
        names = values["X-Amz-SignedHeaders"].split(";")
        header_values = {"host": host, **(headers or {})}
        canonical_headers = "".join(name + ":" + header_values.get(name, "").strip() + "\n" for name in names)
        query = urllib.parse.urlencode(sorted((name, value) for name, value in parameters if name != "X-Amz-Signature"), quote_via=urllib.parse.quote)
        canonical = "\n".join([method, address.path, query, canonical_headers, values["X-Amz-SignedHeaders"], "UNSIGNED-PAYLOAD"])
        scope = values["X-Amz-Credential"].split("/", 1)[1]
        string_to_sign = "AWS4-HMAC-SHA256\n" + values["X-Amz-Date"] + "\n" + scope + "\n" + hashlib.sha256(canonical.encode()).hexdigest()
        key = ("AWS4" + SECRET_KEY).encode()
        for component in scope.split("/"):
            key = hmac.new(key, component.encode(), hashlib.sha256).digest()
        return changed(target, "X-Amz-Signature", hmac.new(key, string_to_sign.encode(), hashlib.sha256).hexdigest())

    with tempfile.TemporaryDirectory(prefix="moon-s3-presign-") as directory:
        environment = dict(os.environ, MOON_S3_ROOT=directory, MOON_S3_LISTEN=host,
                           MOON_S3_ACCESS_KEY=ACCESS_KEY, MOON_S3_SECRET_KEY=SECRET_KEY)
        with tempfile.TemporaryFile() as server_log:
            server = subprocess.Popen([str(PROJECT / "_build/native/debug/build/cmd/main/main.exe")],
                                      env=environment, stdout=server_log, stderr=server_log)
            try:
                for attempt in range(100):
                    if server.poll() is not None:
                        raise RuntimeError("server exited before becoming healthy")
                    try:
                        if request("GET", "/healthz")[0] == 200:
                            break
                    except OSError:
                        pass
                    time.sleep(0.05)
                else:
                    raise RuntimeError("server did not become healthy")
                bucket_path = "/presign-bucket"
                assert request("PUT", bucket_path, headers=sign("PUT", bucket_path, host))[0] == 200
                payload = bytes(range(256)) * 513
                upload_url = url("PUT")
                status, headers, body = request("OPTIONS", upload_url, headers={"Origin": "https://example.test", "Access-Control-Request-Method": "PUT"})
                assert status == 204
                assert headers["Access-Control-Allow-Origin"] == "*"
                assert request("PUT", upload_url, payload, {"Content-Type": "application/octet-stream"})[0] == 200
                download_url = url()
                assert request("GET", download_url)[2] == payload
                assert request("GET", download_url, headers={"Range": "bytes=65530-70000"})[2] == payload[65530:70001]
                status, headers, body = request("HEAD", url("HEAD"))
                assert (status, body) == (200, b"")
                assert headers["Content-Length"] == str(len(payload))
                assert request("GET", download_url, headers={"If-None-Match": headers["ETag"]})[0] == 304
                assert request("GET", object_path)[0] == 403
                assert request("HEAD", download_url)[0] == 403
                assert request("DELETE", download_url)[0] == 403
                assert request("PUT", download_url, b"tampered")[0] == 403
                now = datetime.datetime.now(datetime.timezone.utc)
                assert request("GET", url(date=now - datetime.timedelta(days=1), expires=604800))[0] == 200
                assert request("GET", url(date=now - datetime.timedelta(minutes=2), expires=60))[0] == 403
                assert request("GET", url(date=now + datetime.timedelta(minutes=16)))[0] == 403
                for name, value in [
                    ("X-Amz-Algorithm", "AWS4-HMAC-SHA1"),
                    ("X-Amz-Expires", "0"), ("X-Amz-Expires", "604801"),
                    ("X-Amz-Expires", "2147483648"), ("X-Amz-Expires", "-1"),
                    ("X-Amz-Date", "20260230T120000Z"),
                    ("X-Amz-SignedHeaders", ""), ("X-Amz-Signature", "0" * 64),
                    ("X-Amz-Credential", "other/20261111/us-east-1/s3/aws4_request"),
                ]:
                    status, _, body = request("GET", changed(download_url, name, value))
                    assert status == 403, (name, value, status)
                    assert ET.fromstring(body).findtext("Code") == "AccessDenied"
                for name in ["X-Amz-Algorithm", "X-Amz-Credential", "X-Amz-Date", "X-Amz-Expires", "X-Amz-SignedHeaders", "X-Amz-Signature"]:
                    value = dict(urllib.parse.parse_qsl(urllib.parse.urlsplit(download_url).query))[name]
                    assert request("GET", download_url + "&" + name + "=" + urllib.parse.quote(value, safe=""))[0] == 403
                    address = urllib.parse.urlsplit(download_url)
                    query = urllib.parse.urlencode([(param, value) for param, value in urllib.parse.parse_qsl(address.query) if param != name])
                    assert request("GET", urllib.parse.urlunsplit(address._replace(query=query)))[0] == 403
                assert request("GET", download_url + "&X-Amz-Security-Token=unsupported")[0] == 403
                assert request("GET", resign(download_url + "&response-content-type=text%2Fplain"))[0] == 403
                assert request("GET", download_url + "&extra=changed")[0] == 403
                assert request("GET", download_url.replace("folder/", "other/"))[0] == 403
                assert request("GET", download_url, headers={"Host": "different.example"})[0] == 403
                assert request("GET", download_url, headers=sign("GET", object_path, host))[0] == 403
                for names in ["host;host", "content-type", "host;content-type", "Host", "host;x-missing"]:
                    invalid_url = resign(changed(download_url, "X-Amz-SignedHeaders", names))
                    assert request("GET", invalid_url)[0] == 403, names
                signed_content_type = resign(changed(upload_url, "X-Amz-SignedHeaders", "content-type;host"), "PUT", {"content-type": "text/plain"})
                assert request("PUT", signed_content_type, b"new contents", {"Content-Type": "application/json"})[0] == 403
                assert request("GET", download_url)[2] == payload
                assert request("PUT", signed_content_type, b"new contents", {"Content-Type": "text/plain"})[0] == 200
                assert request("GET", download_url)[2] == b"new contents"
                assert request("PUT", url("PUT", key="empty"), b"")[0] == 200
                assert request("GET", url(key="empty"))[2] == b""
                assert request("GET", url(key="missing"))[0] == 404
                command = ["python3", str(PROJECT / "scripts/presign.py"), "presign-bucket", object_key,
                           "--endpoint", endpoint, "--expires", "60"]
                generated = subprocess.run(command, env=environment, check=True, capture_output=True, text=True).stdout.strip()
                assert request("GET", generated)[2] == b"new contents"
                for invalid_arguments in [["--expires", "0"], ["--expires", "604801"], ["--endpoint", endpoint + "/path"]]:
                    assert subprocess.run(command + invalid_arguments, env=environment, capture_output=True).returncode != 0
                no_credentials = dict(environment)
                for name in ["MOON_S3_ACCESS_KEY", "MOON_S3_SECRET_KEY", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY"]:
                    no_credentials.pop(name, None)
                assert subprocess.run(command, env=no_credentials, capture_output=True).returncode != 0
                if arguments.sdk:
                    import botocore.config
                    import botocore.session

                    client = botocore.session.get_session().create_client(
                        "s3", endpoint_url=endpoint, region_name="us-east-1",
                        aws_access_key_id=ACCESS_KEY, aws_secret_access_key=SECRET_KEY,
                        config=botocore.config.Config(signature_version="s3v4", s3={"addressing_style": "path"}),
                    )
                    try:
                        sdk_key = "sdk/头像 +%&.txt"
                        parameters = {"Bucket": "presign-bucket", "Key": sdk_key}
                        sdk_upload = client.generate_presigned_url("put_object", Params={**parameters, "ContentType": "text/plain"}, ExpiresIn=600)
                        assert request("PUT", sdk_upload, b"sdk contents", {"Content-Type": "text/plain"})[0] == 200
                        sdk_download = client.generate_presigned_url("get_object", Params=parameters, ExpiresIn=600)
                        assert request("GET", sdk_download)[2] == b"sdk contents"
                        sdk_head = client.generate_presigned_url("head_object", Params=parameters, ExpiresIn=600)
                        assert request("HEAD", sdk_head)[0] == 200
                        assert request("PUT", sdk_upload, b"bad contents", {"Content-Type": "application/json"})[0] == 403
                        assert request("GET", sdk_download)[2] == b"sdk contents"
                        print("Botocore interoperability passed: presigned GET, HEAD and signed Content-Type PUT.")
                    finally:
                        client.close()
                print("Presigned regression passed: GET/HEAD/PUT, expiry, tampering, CORS, signed headers and CLI.")
            except BaseException:
                server_log.seek(0)
                print(server_log.read().decode(errors="replace"))
                raise
            finally:
                server.terminate()
                try:
                    server.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    server.kill()
                    server.wait()


if __name__ == "__main__":
    main()
